class MemoryDreamError(Exception):
    """User-facing command failure."""


@dataclass(frozen=True)
class Project:
    id: str
    name: str
    root: Path
    source: Path
    artifact: Path
    cache: Path
    created_at: str
    updated_at: str


def main(argv: list[str] | None = None) -> int:
    parser = make_parser()
    args = parser.parse_args(argv)
    try:
        return args.func(args)
    except MemoryDreamError as exc:
        print(f"memory-dream: error: {exc}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        print("memory-dream: interrupted", file=sys.stderr)
        return 130


def make_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="memory-dream")
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument(
        "--project-root",
        type=Path,
        default=argparse.SUPPRESS,
        help="Resolve or register this project instead of cwd.",
    )
    common.add_argument(
        "--dream-root",
        type=Path,
        default=argparse.SUPPRESS,
        help="Use a non-default management root.",
    )
    parser.add_argument(
        "--project-root",
        type=Path,
        default=argparse.SUPPRESS,
        help="Resolve or register this project instead of cwd.",
    )
    parser.add_argument(
        "--dream-root",
        type=Path,
        default=argparse.SUPPRESS,
        help="Use a non-default management root.",
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    for name, func, help_text in [
        ("init", cmd_init, "register the current project"),
        ("where", cmd_where, "print the current project binding"),
        ("open", cmd_open, "print the source wiki path"),
        ("status", cmd_status, "print project memory status"),
        ("list", cmd_list, "list source notes"),
        ("new", cmd_new, "create a source note via zk-lsp"),
        ("edit", cmd_edit, "print or open a source note path"),
        ("link", cmd_link, "link a source note from index.typ"),
        ("build", cmd_build, "build Markdown artifacts"),
        ("context", cmd_context, "print AI-consumable project memory context"),
        ("show", cmd_show, "print artifact/Memory.md"),
        ("check", cmd_check, "delegate graph checks to zk-lsp"),
    ]:
        sub = subparsers.add_parser(name, parents=[common], help=help_text)
        if name in {"status", "list"}:
            sub.add_argument(
                "--format",
                choices=["text", "json"],
                default="text",
                help="Output format.",
            )
        if name == "new":
            sub.add_argument("--title", required=True, help="Note title.")
            sub.add_argument("--id", help="Custom 10-digit note ID.")
            sub.add_argument(
                "--kind",
                required=True,
                choices=["decision", "experience"],
                help="Memory note kind.",
            )
            sub.add_argument("--content", default="", help="Initial note content.")
            sub.add_argument("--link", action="store_true", help="Link the new note from index.typ.")
            sub.add_argument("--build", action="store_true", help="Build artifacts after creating the note.")
        if name == "edit":
            sub.add_argument("id", help="10-digit note ID.")
            sub.add_argument("--editor", action="store_true", help="Open the note with $EDITOR instead of printing the path.")
        if name == "link":
            sub.add_argument("id", help="10-digit note ID.")
            sub.add_argument("--section", help="Reserved for section-aware linking; currently appends to index.typ.")
            sub.add_argument("--build", action="store_true", help="Build artifacts after linking the note.")
        if name == "context":
            sub.add_argument(
                "--all",
                action="store_true",
                help="Include every generated note artifact instead of only Memory.md references.",
            )
            sub.add_argument(
                "--max-notes",
                type=int,
                default=20,
                help="Maximum referenced notes to include unless --all is set.",
            )
        sub.set_defaults(func=func)

    return parser


def cmd_init(args: argparse.Namespace) -> int:
    dream_root = resolve_dream_root(args)
    project_arg = getattr(args, "project_root", None)
    project_root = resolve_project_root(project_arg, dream_root, for_init=True)
    validate_project_root(project_root)
    with registry_lock(dream_root):
        registry = load_registry(dream_root)
        existing = find_project_by_root(registry, project_root)
        if existing is None and project_arg is None and find_git_root(Path.cwd().resolve()) is None:
            existing = find_project_containing_path(registry, Path.cwd().resolve())
        if existing:
            print_binding(existing)
            return 0

        project = new_project(dream_root, project_root)

        ensure_new_project_dirs(project)
        try:
            run_zk_lsp(["init"], cwd=project.source)
        except Exception:
            remove_unregistered_project_dir(dream_root, project)
            raise

        now = iso_now()
        project = Project(
            id=project.id,
            name=project.name,
            root=project.root,
            source=project.source,
            artifact=project.artifact,
            cache=project.cache,
            created_at=now,
            updated_at=now,
        )
        registry.append(project)
        write_registry(dream_root, registry)
        print_binding(project)
    return 0


