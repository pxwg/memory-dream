def validate_note_id(note_id: str) -> None:
    if not re.fullmatch(r"\d{10}", note_id):
        raise MemoryDreamError(f"invalid note id: {note_id}")


def next_note_id(project: Project) -> str:
    existing = {path.stem for path in (project.source / "note").glob("*.typ")}
    candidate = datetime.now().replace(second=0, microsecond=0)
    for _ in range(1440):
        note_id = candidate.strftime("%y%m%d%H%M")
        if note_id not in existing:
            return note_id
        candidate += timedelta(minutes=1)
    raise MemoryDreamError("could not allocate an unused note id")


def link_note(project: Project, note_id: str) -> None:
    validate_note_id(note_id)
    note_path_for_id(project, note_id)
    index_path = project.source / "index.typ"
    with file_lock(project.source.parent / ".index.lock"):
        text = index_path.read_text(encoding="utf-8")
        if re.search(rf"@{re.escape(note_id)}(?!\d)", uncommented_typst_text(text)):
            return
        suffix = "" if text.endswith("\n") else "\n"
        atomic_write_text(index_path, f"{text}{suffix}- @{note_id}\n")


def uncommented_typst_text(text: str) -> str:
    return "\n".join(line for line in text.splitlines() if not line.lstrip().startswith("//"))


def atomic_write_text(path: Path, text: str) -> None:
    with tempfile.NamedTemporaryFile(
        "w",
        encoding="utf-8",
        dir=path.parent,
        prefix=f".{path.name}.",
        suffix=".tmp",
        delete=False,
    ) as file:
        tmp_path = Path(file.name)
        file.write(text)
        file.flush()
        os.fsync(file.fileno())
    try:
        tmp_path.replace(path)
        fsync_directory(path.parent)
    except Exception:
        tmp_path.unlink(missing_ok=True)
        raise


def build_artifacts(project: Project) -> None:
    index_path = project.source / "index.typ"
    note_dir = project.source / "note"
    notes = sorted(note_dir.glob("*.typ"))
    note_infos = [parse_note_info(path) for path in notes]
    validate_note_infos(note_infos)
    link_map = {
        info["id"]: {
            "title": info["title"],
            "filename": artifact_name(info["id"], info["title"]),
        }
        for info in note_infos
    }

    staging = create_artifact_staging_dir(project)
    try:
        memory_dir = staging / "memory"
        memory_dir.mkdir(parents=True, exist_ok=True)

        index_text = index_path.read_text(encoding="utf-8")
        (staging / "Memory.md").write_text(
            normalize_typst(
                index_text,
                source="index.typ",
                link_map=link_map,
                note_id=None,
                title=None,
                link_prefix="memory/",
            ),
            encoding="utf-8",
        )

        for path, info in zip(notes, note_infos, strict=True):
            rel_source = f"note/{path.name}"
            output = memory_dir / artifact_name(info["id"], info["title"])
            output.write_text(
                normalize_typst(
                    path.read_text(encoding="utf-8"),
                    source=rel_source,
                    link_map=link_map,
                    note_id=info["id"],
                    title=info["title"],
                    link_prefix="",
                ),
                encoding="utf-8",
            )
        swap_artifact_dir(project, staging)
    except Exception:
        if staging.exists():
            shutil.rmtree(staging, ignore_errors=True)
        raise


def render_context(project: Project, *, include_all: bool, max_notes: int) -> str:
    memory_file = project.artifact / "Memory.md"
    memory_text = memory_file.read_text(encoding="utf-8")
    note_dir = project.artifact / "memory"
    if include_all:
        note_paths = sorted(note_dir.glob("*.md")) if note_dir.exists() else []
        omitted = 0
    else:
        referenced = extract_memory_links(memory_text)
        if max_notes:
            selected = referenced[:max_notes]
            omitted = max(0, len(referenced) - len(selected))
        else:
            selected = []
            omitted = len(referenced)
        note_paths = [project.artifact / href for href in selected]

    missing = [path for path in note_paths if not path.is_file()]
    if missing:
        paths = ", ".join(str(path) for path in missing)
        raise MemoryDreamError(f"context references missing note artifacts: {paths}; run `memory-dream build`")

    parts = [
        "# Project Memory Context",
        "",
        "## Paths",
        "",
        f"- project-root: `{project.root}`",
        f"- source-root: `{project.source}`",
        f"- artifact-root: `{project.artifact}`",
        f"- memory-entry: `{memory_file}`",
        f"- note-artifacts: `{note_dir}`",
        f"- source-notes: `{project.source / 'note'}`",
        "",
        "## Memory.md",
        "",
        memory_text.rstrip(),
    ]

    if note_paths:
        parts.extend(["", "## Referenced Notes" if not include_all else "## All Notes"])
        for path in note_paths:
            parts.extend(
                [
                    "",
                    f"### {path.name}",
                    "",
                    f"- artifact: `{path}`",
                    f"- source-candidate: `{project.source / 'note' / (note_id_from_artifact(path.name) + '.typ')}`",
                    "",
                    path.read_text(encoding="utf-8").rstrip(),
                ]
            )

    if omitted:
        parts.extend(["", f"<!-- {omitted} referenced note(s) omitted by --max-notes. -->"])

    return "\n".join(parts).rstrip() + "\n"


def ensure_context_artifacts_current(project: Project) -> None:
    reason = context_stale_reason(project)
    if reason is not None:
        raise MemoryDreamError(reason)


def context_stale_reason(project: Project) -> str | None:
    try:
        require_source_wiki(project)
    except MemoryDreamError as exc:
        return str(exc)
    memory_file = project.artifact / "Memory.md"
    if not memory_file.exists():
        return f"artifact missing: {memory_file}; run `memory-dream build`"
    index_path = project.source / "index.typ"
    if source_newer_than_artifact(index_path, memory_file):
        return stale_context_message(index_path, memory_file)

    expected_artifacts: set[str] = set()
    for note_path in sorted((project.source / "note").glob("*.typ")):
        info = parse_note_info(note_path)
        artifact = project.artifact / "memory" / artifact_name(info["id"], info["title"])
        expected_artifacts.add(artifact.name)
        if not artifact.exists():
            return f"artifact stale: missing {artifact}; run `memory-dream build`"
        if source_newer_than_artifact(note_path, artifact):
            return stale_context_message(note_path, artifact)

    artifact_dir = project.artifact / "memory"
    if artifact_dir.exists():
        orphaned = sorted(path for path in artifact_dir.glob("*.md") if path.name not in expected_artifacts)
        if orphaned:
            paths = ", ".join(str(path) for path in orphaned)
            return f"artifact stale: orphaned note artifact(s): {paths}; run `memory-dream build`"
    return None


def source_newer_than_artifact(source: Path, artifact: Path) -> bool:
    return source.stat().st_mtime_ns > artifact.stat().st_mtime_ns


def stale_context_message(source: Path, artifact: Path) -> str:
    return f"artifact stale: {source} is newer than {artifact}; run `memory-dream build`"


def extract_memory_links(text: str) -> list[Path]:
    links: list[Path] = []
    seen: set[Path] = set()
    for match in re.finditer(r"\[[^\]]*]\((memory/[^)\s]+\.md)\)", text):
        href = Path(match.group(1))
        if href.is_absolute() or ".." in href.parts or href.parts[0] != "memory":
            continue
        if href not in seen:
            links.append(href)
            seen.add(href)
    for match in re.finditer(r"(?<!!)\[\[memory/([^\]\s]+\.md)]]", text):
        href = Path("memory") / match.group(1)
        if ".." in href.parts:
            continue
        if href not in seen:
            links.append(href)
            seen.add(href)
    return links


def note_id_from_artifact(filename: str) -> str:
    return filename.split("-", 1)[0]


def validate_artifact_dir(project: Project) -> None:
    validate_project_id(project.id, Path("runtime project"))
    artifact = project.artifact
    expected = (project.source.parent / "artifact").resolve()
    if project.source.parent.name != project.id:
        raise MemoryDreamError(f"refusing to clean artifact for invalid project directory: {project.source.parent}")
    if project.cache.parent != project.source.parent:
        raise MemoryDreamError(f"refusing to clean artifact for inconsistent project paths: {project.id}")
    if artifact.resolve() != expected:
        raise MemoryDreamError(f"refusing to clean unmanaged artifact directory: {artifact}")


def create_artifact_staging_dir(project: Project) -> Path:
    validate_artifact_dir(project)
    project_dir = project.source.parent
    return Path(tempfile.mkdtemp(prefix=".artifact.", suffix=".tmp", dir=project_dir))


def swap_artifact_dir(project: Project, staging: Path) -> None:
    validate_artifact_dir(project)
    artifact = project.artifact
    project_dir = project.source.parent
    backup = project_dir / f".artifact.{os.getpid()}.bak"
    if backup.exists():
        shutil.rmtree(backup)
    try:
        if artifact.exists():
            artifact.rename(backup)
        staging.rename(artifact)
        if backup.exists():
            shutil.rmtree(backup)
    except Exception:
        if not artifact.exists() and backup.exists():
            backup.rename(artifact)
        if staging.exists():
            shutil.rmtree(staging, ignore_errors=True)
        raise


def parse_note_info(path: Path) -> dict[str, str]:
    text = path.read_text(encoding="utf-8")
    match = re.search(r"^=\s*(.*?)\s+<(\d{10})>\s*$", text, flags=re.MULTILINE)
    if not match:
        raise MemoryDreamError(f"invalid note header: {path}")
    return {"title": match.group(1).strip(), "id": match.group(2), "path": str(path)}


def validate_note_infos(note_infos: list[dict[str, str]]) -> None:
    seen_ids: dict[str, str] = {}
    seen_artifacts: dict[str, str] = {}
    for info in note_infos:
        note_id = info["id"]
        path = Path(info["path"])
        if path.stem != note_id:
            raise MemoryDreamError(f"note filename does not match header id: {path} declares <{note_id}>")
        if note_id in seen_ids:
            raise MemoryDreamError(f"duplicate note id {note_id}: {seen_ids[note_id]} and {path}")
        artifact = artifact_name(note_id, info["title"])
        if artifact in seen_artifacts:
            raise MemoryDreamError(f"duplicate artifact filename {artifact}: {seen_artifacts[artifact]} and {path}")
        seen_ids[note_id] = str(path)
        seen_artifacts[artifact] = str(path)


def artifact_name(note_id: str, title: str) -> str:
    return f"{note_id}-{slugify(title) or 'note'}.md"


def slugify(value: str) -> str:
    slug = re.sub(r"[^a-zA-Z0-9]+", "-", value.strip().lower()).strip("-")
    return slug or re.sub(r"[^0-9a-zA-Z]+", "-", value.strip()).strip("-").lower()


def normalize_typst(
    text: str,
    *,
    source: str,
    link_map: dict[str, dict[str, str]],
    note_id: str | None,
    title: str | None,
    link_prefix: str,
) -> str:
    metadata, body = extract_metadata(text)
    tags, body_lines = extract_tags_and_body(body.splitlines())
    body_text = "\n".join(normalize_line(line, link_map, link_prefix) for line in body_lines).strip()
    frontmatter = render_frontmatter(metadata, source=source, tags=tags, note_id=note_id, title=title)
    return f"{GENERATED_MARKER}\n\n{frontmatter}\n\n{body_text}\n"


def extract_metadata(text: str) -> tuple[str, str]:
    lines = text.splitlines()
    start = None
    fence = None
    end = None
    expression_end = None
    for idx, line in enumerate(lines):
        stripped = line.strip()
        if start is None and stripped.startswith("#let zk-metadata") and "toml(bytes(" in stripped:
            start = idx
            continue
        if start is not None and fence is None and stripped == "```toml":
            fence = idx
            continue
        if fence is not None and stripped.startswith("```"):
            end = idx
            break
    if start is None or fence is None or end is None:
        return "", "\n".join(lines)
    for idx in range(end + 1, len(lines)):
        stripped = lines[idx].strip()
        if stripped.startswith("#show:"):
            break
        expression_end = idx
        if "))" in stripped:
            break
    metadata = "\n".join(lines[fence + 1 : end])
    drop_end = expression_end if expression_end is not None else end
    body_lines = lines[:start] + lines[drop_end + 1 :]
    return metadata, "\n".join(body_lines)


def extract_tags_and_body(lines: list[str]) -> tuple[list[str], list[str]]:
    tags: list[str] = []
    body: list[str] = []
    for line in lines:
        stripped = line.strip()
        if stripped.startswith("#import "):
            continue
        if stripped.startswith("#include "):
            continue
        if stripped.startswith("#show:"):
            continue
        if stripped.startswith("#status_tag("):
            continue
        if stripped.startswith("//"):
            continue
        tag_matches = re.findall(r"#tag\.([A-Za-z0-9_-]+)", line)
        if tag_matches and stripped.replace(" ", "") == "".join(f"#tag.{tag}" for tag in tag_matches):
            tags.extend(tag_matches)
            continue
        if tag_matches:
            tags.extend(tag_matches)
            line = re.sub(r"#tag\.[A-Za-z0-9_-]+", "", line).rstrip()
            if not line.strip():
                continue
        body.append(line)
    return sorted(set(tags)), body


def normalize_line(line: str, link_map: dict[str, dict[str, str]], link_prefix: str) -> str:
    heading = re.match(r"^(=+)\s+(.+)$", line)
    if heading:
        level = len(heading.group(1))
        text = re.sub(r"\s+<\d{10}>\s*$", "", heading.group(2)).strip()
        return f"{'#' * level} {replace_refs(text, link_map, link_prefix)}"
    return replace_refs(line, link_map, link_prefix)


def replace_refs(line: str, link_map: dict[str, dict[str, str]], link_prefix: str) -> str:
    def repl(match: re.Match[str]) -> str:
        ref = match.group(1)
        target = link_map.get(ref)
        if target is None:
            return f"@{ref}"
        return f"[{target['title']} @{ref}]({link_prefix}{target['filename']})"

    return re.sub(r"@(\d{10})", repl, line)


def render_frontmatter(
    metadata: str,
    *,
    source: str,
    tags: list[str],
    note_id: str | None,
    title: str | None,
) -> str:
    lines = ["+++"]
    if note_id:
        lines.append(f'id = "{toml_escape(note_id)}"')
    if title:
        lines.append(f'title = "{toml_escape(title)}"')
    lines.append(f'source = "{toml_escape(source)}"')
    if tags:
        lines.append("tags = [" + ", ".join(f'"{toml_escape(tag)}"' for tag in tags) + "]")
    metadata_lines = filter_reserved_frontmatter_keys(metadata)
    if metadata_lines:
        lines.extend(metadata_lines)
    lines.append("+++")
    frontmatter = "\n".join(lines)
    try:
        tomllib.loads("\n".join(lines[1:-1]))
    except tomllib.TOMLDecodeError as exc:
        raise MemoryDreamError(f"invalid normalized frontmatter for {source}: {exc}") from exc
    return frontmatter


def filter_reserved_frontmatter_keys(metadata: str) -> list[str]:
    lines: list[str] = []
    in_table = False
    for line in metadata.splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        if stripped.startswith("["):
            in_table = True
            lines.append(line.rstrip())
            continue
        if not in_table:
            key = top_level_toml_key(stripped)
            if key in RESERVED_FRONTMATTER_KEYS:
                continue
        lines.append(line.rstrip())
    return lines


def top_level_toml_key(stripped_line: str) -> str | None:
    if stripped_line.startswith('"'):
        escaped = False
        chars: list[str] = []
        for char in stripped_line[1:]:
            if escaped:
                chars.append(char)
                escaped = False
                continue
            if char == "\\":
                escaped = True
                continue
            if char == '"':
                rest = stripped_line[len(chars) + 2 :].lstrip()
                return "".join(chars) if rest.startswith("=") else None
            chars.append(char)
        return None
    if stripped_line.startswith("'"):
        end = stripped_line.find("'", 1)
        if end == -1:
            return None
        rest = stripped_line[end + 1 :].lstrip()
        return stripped_line[1:end] if rest.startswith("=") else None
    match = re.match(r"^([A-Za-z0-9_-]+)\s*=", stripped_line)
    return match.group(1) if match else None


def iso_now() -> str:
    return datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds")
